std::string MakeTempDirectory() {
  NSString *dir = [NSTemporaryDirectory()
      stringByAppendingPathComponent:[[NSUUID UUID] UUIDString]];
  [[NSFileManager defaultManager] createDirectoryAtPath:dir
                            withIntermediateDirectories:YES
                                             attributes:nil
                                                  error:nil];
  return dir.UTF8String;
}

void WriteFile(const std::string &path, absl::string_view content) {
  NSData *data = [NSData dataWithBytes:content.data() length:content.size()];
  ASSERT_TRUE([data writeToFile:@(path.c_str()) atomically:YES]);
}

TEST(DebugLogExportTest, PutsTheLogsTogetherOldestFirst) {
  const std::string dir = MakeTempDirectory();
  WriteFile(dir + "/zenz_debug.log", "new zenz\n");
  WriteFile(dir + "/zenz_debug.log.1", "old zenz\n");
  WriteFile(dir + "/candidate_position.log", "position");

  std::string bundle;
  ASSERT_TRUE(BuildDebugLogBundle(dir, "version: test\n", &bundle));
  EXPECT_TRUE(absl::StartsWith(bundle, "Mozlumi debug log\nversion: test\n"));
  const size_t old_zenz = bundle.find("old zenz");
  const size_t new_zenz = bundle.find("new zenz");
  ASSERT_NE(old_zenz, std::string::npos);
  ASSERT_NE(new_zenz, std::string::npos);
  EXPECT_LT(old_zenz, new_zenz);
  EXPECT_NE(
      bundle.find("===== candidate_position.log (8 bytes) =====\nposition\n"),
      std::string::npos);
  EXPECT_EQ(bundle.find("candidate_position.log.1"), std::string::npos);
}

TEST(DebugLogExportTest, ReturnsFalseWithoutLogs) {
  std::string bundle;
  EXPECT_FALSE(
      BuildDebugLogBundle(MakeTempDirectory(), "version: test\n", &bundle));
}

TEST(DebugLogExportTest, OnlyThePrivateKeyCanReadTheFile) {
  NSDictionary *attributes = @{
    (__bridge id)kSecAttrKeyType : (__bridge id)kSecAttrKeyTypeECSECPrimeRandom,
    (__bridge id)kSecAttrKeySizeInBits : @256,
  };
  CFErrorRef error = nullptr;
  SecKeyRef private_key =
      SecKeyCreateRandomKey((__bridge CFDictionaryRef)attributes, &error);
  ASSERT_NE(private_key, nullptr);
  SecKeyRef public_key = SecKeyCopyPublicKey(private_key);
  ASSERT_NE(public_key, nullptr);
  CFDataRef public_data = SecKeyCopyExternalRepresentation(public_key, &error);
  ASSERT_NE(public_data, nullptr);
  ASSERT_EQ(CFDataGetLength(public_data), 65);

  const std::string plaintext = "Mozlumi debug log\nplaced=(1,2,3,4)\n";
  std::string file_content;
  ASSERT_TRUE(EncryptDebugLogBundle(
      absl::MakeConstSpan(CFDataGetBytePtr(public_data),
                          static_cast<size_t>(CFDataGetLength(public_data))),
      plaintext, &file_content));
  ASSERT_TRUE(absl::StartsWith(file_content, kDebugLogFileMagic));
  EXPECT_EQ(file_content.find("placed="), std::string::npos);

  NSData *encrypted =
      [NSData dataWithBytes:file_content.data() + kDebugLogFileMagic.size()
                     length:file_content.size() - kDebugLogFileMagic.size()];
  CFDataRef decrypted = SecKeyCreateDecryptedData(
      private_key,
      kSecKeyAlgorithmECIESEncryptionCofactorVariableIVX963SHA256AESGCM,
      (__bridge CFDataRef)encrypted, &error);
  ASSERT_NE(decrypted, nullptr);
  EXPECT_EQ(std::string(reinterpret_cast<const char *>(CFDataGetBytePtr(decrypted)),
                        static_cast<size_t>(CFDataGetLength(decrypted))),
            plaintext);

  CFRelease(decrypted);
  CFRelease(public_data);
  CFRelease(public_key);
  CFRelease(private_key);
}

TEST(DebugLogExportTest, RejectsAnInvalidPublicKey) {
  const uint8_t zeros[65] = {};
  std::string file_content;
  EXPECT_FALSE(EncryptDebugLogBundle(zeros, "text", &file_content));
  EXPECT_TRUE(file_content.empty());
}

// The public key generated by tools/mozlumi_debug_log/keygen.swift.
TEST(DebugLogExportTest, TheBundledPublicKeyIsValid) {
  EXPECT_EQ(sizeof(kMozlumiDebugPublicKey), 65u);
  std::string file_content;
  EXPECT_TRUE(
      EncryptDebugLogBundle(kMozlumiDebugPublicKey, "text", &file_content));
}

