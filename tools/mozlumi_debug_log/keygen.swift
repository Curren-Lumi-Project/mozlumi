// Mozlumi (1.3.4): makes the key pair for the encrypted debug log.
//
//   swift keygen.swift <private key file> <public key header>
//
// The private key file is created with permission 600. Keep it only on the
// developer's Mac, never in the repository, and keep a backup: without it the
// exported logs cannot be read. The public key header is
// src/mac/mozlumi_debug_public_key.h.

import Foundation
import Security

func fail(_ message: String) -> Never {
  FileHandle.standardError.write((message + "\n").data(using: .utf8)!)
  exit(1)
}

let arguments = CommandLine.arguments
guard arguments.count == 3 else {
  FileHandle.standardError.write(
    "usage: swift keygen.swift <private key file> <public key header>\n".data(using: .utf8)!)
  exit(2)
}
let privateKeyPath = arguments[1]
let headerPath = arguments[2]
if FileManager.default.fileExists(atPath: privateKeyPath) {
  fail("\(privateKeyPath) already exists. It is not overwritten.")
}

let attributes: [String: Any] = [
  kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
  kSecAttrKeySizeInBits as String: 256,
]
var error: Unmanaged<CFError>?
guard let privateKey = SecKeyCreateRandomKey(attributes as CFDictionary, &error) else {
  fail("SecKeyCreateRandomKey failed: \(String(describing: error?.takeRetainedValue()))")
}
guard let publicKey = SecKeyCopyPublicKey(privateKey),
  let publicData = SecKeyCopyExternalRepresentation(publicKey, &error) as Data?,
  let privateData = SecKeyCopyExternalRepresentation(privateKey, &error) as Data?
else {
  fail("SecKeyCopyExternalRepresentation failed: \(String(describing: error?.takeRetainedValue()))")
}
guard publicData.count == 65 else {
  fail("unexpected public key length: \(publicData.count)")
}

guard
  FileManager.default.createFile(
    atPath: privateKeyPath, contents: privateData,
    attributes: [.posixPermissions: 0o600])
else {
  fail("cannot write \(privateKeyPath)")
}

let bytes = publicData.map { String(format: "0x%02x", $0) }
var rows: [String] = []
var index = 0
while index < bytes.count {
  let end = min(index + 12, bytes.count)
  rows.append("    " + bytes[index..<end].joined(separator: ", ") + ",")
  index = end
}
let header = """
  // Copyright 2026
  // Licensed under the same terms as Mozc.
  //
  // Generated by tools/mozlumi_debug_log/keygen.swift. The public key of the
  // Mozlumi developer for the encrypted debug log (mac/debug_log_export.h).
  // The private key is kept only on the developer's Mac and is never in this
  // repository.

  #ifndef MOZC_MAC_MOZLUMI_DEBUG_PUBLIC_KEY_H_
  #define MOZC_MAC_MOZLUMI_DEBUG_PUBLIC_KEY_H_

  #include <cstdint>

  namespace mozc {
  namespace mac {

  // P-256 public key (ANSI X9.63, uncompressed, 65 bytes).
  inline constexpr uint8_t kMozlumiDebugPublicKey[] = {
  \(rows.joined(separator: "\n"))
  };

  }  // namespace mac
  }  // namespace mozc

  #endif  // MOZC_MAC_MOZLUMI_DEBUG_PUBLIC_KEY_H_

  """
do {
  try header.write(toFile: headerPath, atomically: true, encoding: .utf8)
} catch {
  fail("cannot write \(headerPath): \(error)")
}
print("private key: \(privateKeyPath) (keep a backup; never commit it)")
print("public key header: \(headerPath)")
